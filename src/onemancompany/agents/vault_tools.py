"""Vault tools for the DSI (or the COO until the company has one).

The DSI keeps the company's logins in the vault (core/vault.py) and decides
who may use each one. None of these tools ever returns a value: passwords
are generated by OneManCompany's code, typed by the CEO in their own
interface, or (later) captured from a page by the browser, and employees use
them through actions that OneManCompany performs for them.
"""

from __future__ import annotations

from langchain_core.tools import tool


def _actor(employee_id: str) -> str:
    from onemancompany.agents.access_tools import _actor as desk_actor

    return desk_actor(employee_id)


def _err(exc: Exception) -> dict:
    return {"status": "error", "message": str(exc)}


@tool
def vault_list(for_employee: str = "") -> dict:
    """List the company vault: logins and notes, who may use each one, never a value.

    Args:
        for_employee: Optional employee id: only the items this employee may use.
    """
    from onemancompany.core import vault

    items = vault.list_items(for_employee or None)
    return {"items": [{k: i.get(k) for k in ("id", "name", "kind", "service", "url", "username", "holders",
                                             "holder_labels", "has_password", "has_totp", "has_note", "ask",
                                             "last_used", "updated_at")} for i in items]}


@tool
def vault_add_login(name: str, service: str, url: str = "", username: str = "", holders: list[str] | None = None,
                    generate_password: bool = True, length: int = 24, symbols: bool = True, note: str = "",
                    employee_id: str = "") -> dict:
    """Add a login to the vault, with a strong password generated by OneManCompany (never shown).

    Use it when you create an account (the password goes in the vault before
    anyone types it) or to prepare an item the CEO will fill (generate_password
    False, then vault_ask_ceo). Name items so anyone understands them, e.g.
    "Scaleway — Léa Martin (Le Diplomate)".

    Args:
        name: Item name.
        service: The service, e.g. "Scaleway".
        url: The sign-in page.
        username: The login (an email address, a user name).
        holders: Employee ids who may use it ("*" = everyone). Give the minimum.
        generate_password: True (default): a random password is generated and stored.
        length: Password length (default 24).
        symbols: False if the site refuses special characters.
        note: Non-secret note (what the account is for, recovery hints).
        employee_id: Your employee ID (auto-filled).
    """
    from onemancompany.core import vault

    try:
        item = vault.create_item(name, service=service, url=url, username=username, holders=holders or [],
                                 by=_actor(employee_id), generate_password=generate_password, length=length,
                                 symbols=symbols, note=note)
    except ValueError as exc:
        return _err(exc)
    return {"status": "added", "item_id": item["id"], "name": item["name"], "has_password": item["has_password"],
            "message": "In the vault. Nobody sees the password; employees in holders use it through OneManCompany."}


@tool
def vault_new_password(item_id: str, length: int = 24, symbols: bool = True, employee_id: str = "") -> dict:
    """Replace the stored password with a new random one (never shown).

    Only do this when the password is being changed on the site at the same
    time; otherwise the stored password no longer matches the account.

    Args:
        item_id: The vault item.
        length: Password length (default 24).
        symbols: False if the site refuses special characters.
        employee_id: Your employee ID (auto-filled).
    """
    from onemancompany.core import vault

    try:
        vault.generate_password(item_id, by=_actor(employee_id), length=length, symbols=symbols)
    except ValueError as exc:
        return _err(exc)
    return {"status": "replaced", "item_id": item_id}


@tool
def vault_grant(item_id: str, target_employee_id: str, reason: str, employee_id: str = "") -> dict:
    """Let an employee use a vault item (they never see the value). Traced with the reason.

    Args:
        item_id: The vault item.
        target_employee_id: The employee, or "*" for the whole company (shared logins only).
        reason: Why, for which work.
        employee_id: Your employee ID (auto-filled).
    """
    from onemancompany.core import vault

    current = vault.get_item(item_id) or {}
    if str(target_employee_id) == str(employee_id) and current and current.get("created_by") != vault.KEEPER:
        return {"status": "error", "message": "Only the CEO can let you use a login they added (🔑 › Vault › Who "
                                              "can use it). Ask them with vault_ask_ceo if you need it."}
    try:
        item = vault.grant(item_id, target_employee_id, by=_actor(employee_id), reason=reason)
    except ValueError as exc:
        return _err(exc)
    return {"status": "granted", "item_id": item_id, "holders": item["holders"]}


@tool
def vault_revoke(item_id: str, target_employee_id: str, reason: str = "", employee_id: str = "") -> dict:
    """Stop an employee from using a vault item. Traced with the reason.

    Args:
        item_id: The vault item.
        target_employee_id: The employee (or "*").
        reason: Why.
        employee_id: Your employee ID (auto-filled).
    """
    from onemancompany.core import vault

    try:
        item = vault.revoke(item_id, target_employee_id, by=_actor(employee_id), reason=reason)
    except ValueError as exc:
        return _err(exc)
    return {"status": "revoked", "item_id": item_id, "holders": item["holders"]}


@tool
def vault_ask_ceo(item_id: str, what: str, field: str = "password", employee_id: str = "") -> dict:
    """Ask the CEO to type a value only they have (a current password, a 2FA secret, a note).

    The request appears in the CEO's 🔑 box; the CEO types the value there,
    never in a chat. Use it rarely: prefer creating the account yourself with a
    generated password.

    Args:
        item_id: The vault item to fill.
        what: What the CEO must type, in their language, e.g. "Le mot de passe actuel du compte OVH".
        field: "password" (default), "totp" (2FA secret or otpauth:// link) or "note".
        employee_id: Your employee ID (auto-filled).
    """
    from onemancompany.core import vault

    try:
        vault.ask_ceo(item_id, field, what, by=_actor(employee_id), asker=employee_id)
    except ValueError as exc:
        return _err(exc)
    return {"status": "asked", "item_id": item_id,
            "message": "The CEO sees it in their 🔑 box. Carry on with other work; the item is filled when they answer."}


VAULT_ADMIN_TOOLS = [vault_list, vault_add_login, vault_new_password, vault_grant, vault_revoke, vault_ask_ceo]
